    generated = []
    for p in POLICIES:
        decl = DeclarativePolicy(**p)
        out_file = TARGET_DIR / f"{decl.policy_id}.json"
        with open(out_file, "w", encoding="utf-8") as f:
            json.dump(decl.model_dump(), f, indent=2)
